function readStoredLayouts(): ResponsiveLayouts {
  if (typeof window === "undefined") return DEFAULT_LAYOUTS;
  try {
    const parsed: unknown = JSON.parse(window.localStorage.getItem(LAYOUT_KEY) ?? "null");
    if (parsed && typeof parsed === "object" && Object.values(parsed).every(Array.isArray)) {
      return parsed as ResponsiveLayouts;
    }
  } catch {
    /* storage unavailable or corrupt */
  }
  return DEFAULT_LAYOUTS;
}

/* ------------------------------- Helpers -------------------------------- */

const round2 = (v: number | null) => (v === null ? null : Math.round(v * 100) / 100);
const periodOf = (r: MisRecord) => `${r.year}-${String(r.month).padStart(2, "0")}`;

function quantileBreaks(values: number[], classes = PALETTE.length): number[] {
  const unique = [...new Set(values)].sort((a, b) => a - b);
  if (unique.length < 2) return [];
  const n = Math.min(classes, unique.length);
  const breaks: number[] = [];
  for (let i = 1; i < n; i++) breaks.push(unique[Math.floor((i * unique.length) / n) - 1]);
  return [...new Set(breaks)];
}

/** Spread the classes in use across the whole palette, light → dark. */
const paletteAt = (index: number, breakCount: number) =>
  PALETTE[breakCount ? Math.round((index * (PALETTE.length - 1)) / breakCount) : 0];

const classColor = (index: number, breaks: number[], metric: MeasureKey) =>
  metric === "cases" ? CASE_PALETTE[index] : paletteAt(index, breaks.length);

function mapColor(value: number | null, breaks: number[], metric: MeasureKey): string {
  if (value === null) return NO_DATA;
  return classColor(breaks.filter((b) => value > b).length, breaks, metric);
}

const isReliable = (s: AreaStat, metric: MeasureKey) => !isIndicator(metric) || s.totals.tests >= MIN_TESTS_FOR_RANKING;

function escapeHtml(s: string): string {
  return s.replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c] ?? c);
}

const geoCache = new Map<string, Promise<FeatureCollection>>();

function loadGeoJson(url: string): Promise<FeatureCollection> {
  let pending = geoCache.get(url);
  if (!pending) {
    pending = fetch(url).then(async (res) => {
      if (!res.ok) throw new Error(`${url} → HTTP ${res.status}`);
      return (await res.json()) as FeatureCollection;
    });
    pending.catch(() => geoCache.delete(url));
    geoCache.set(url, pending);
  }
  return pending;
}

